-- 3. Tabla de citas
-- La restricción UNIQUE (fecha, hora) garantiza que no se puedan agendar dos citas el mismo día a la misma hora.
CREATE TABLE IF NOT EXISTS citas (
  id          INTEGER     PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  usuario_id  INTEGER     NOT NULL REFERENCES usuarios(id) ON DELETE CASCADE,
  mascota     TEXT        NOT NULL,
  especie     TEXT        NOT NULL CHECK (especie IN ('Perro', 'Gato', 'Otro')),
  servicio    TEXT        NOT NULL,
  notas       TEXT,
  fecha       DATE        NOT NULL,
  hora        TEXT        NOT NULL,
  creado_en   TIMESTAMPTZ NOT NULL DEFAULT now(),
  UNIQUE (fecha, hora)
);

CREATE INDEX IF NOT EXISTS idx_citas_usuario ON citas(usuario_id, fecha, hora);
CREATE INDEX IF NOT EXISTS idx_citas_fecha ON citas(fecha, hora);
